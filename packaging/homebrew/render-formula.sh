#!/usr/bin/env bash
# Write the Homebrew formula for one release to stdout.
#
#   render-formula.sh VERSION SHA256_ARM64 SHA256_X64 [BASE_URL]
#
# BASE_URL defaults to the GitHub Release for vVERSION. The release workflow runs this and commits
# the result to mgpeter/homebrew-tap as Formula/spec-watcher.rb; pass a file:// BASE_URL to try a
# locally built tarball with a local tap.
set -euo pipefail

if [[ $# -lt 3 ]]; then
  echo "usage: $0 VERSION SHA256_ARM64 SHA256_X64 [BASE_URL]" >&2
  exit 64
fi

version="$1"
sha_arm64="$2"
sha_x64="$3"
base_url="${4:-https://github.com/mgpeter/spec-watcher/releases/download/v${version}}"

cat <<RUBY
# Generated by packaging/homebrew/render-formula.sh in mgpeter/spec-watcher. Do not edit by hand:
# the release workflow overwrites this file on every vX.Y.Z tag.
class SpecWatcher < Formula
  desc "Terminal dashboard for a repository's specs folder"
  homepage "https://github.com/mgpeter/spec-watcher"
  version "${version}"
  license "MIT"

  depends_on :macos

  on_macos do
    on_arm do
      url "${base_url}/spec-watcher-${version}-osx-arm64.tar.gz"
      sha256 "${sha_arm64}"
    end
    on_intel do
      url "${base_url}/spec-watcher-${version}-osx-x64.tar.gz"
      sha256 "${sha_x64}"
    end
  end

  def install
    bin.install "spec-watcher"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/spec-watcher --version")

    (testpath/"docs/specs/2026-01-01-sample/spec.md").write <<~MD
      # Spec

      > Spec: Sample Spec
      > Status: Planning
    MD
    output = shell_output("#{bin}/spec-watcher #{testpath} --once --format json")
    assert_match "Sample Spec", output
  end
end
RUBY
